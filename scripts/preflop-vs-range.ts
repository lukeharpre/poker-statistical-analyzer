// Generates src/engine/preflopVsRange.ts: each starting hand's all-in equity against a
// typical continuing range, the top 30% of hands by equity against a random hand.
// Ranking hands by this, not by equity against one random hand, credits what holds up
// against hands that actually play: pairs and suited connectors over weak offsuit kings.
// Run: npx vite-node scripts/preflop-vs-range.ts
import { writeFileSync } from 'node:fs';
import { evaluate } from '../src/engine/evaluator';
import { randomPercentile } from '../src/engine/ranges';

const SAMPLES = 120_000; // standard error ≈ 0.15 percentage points per hand class
const TOP = 0.3;

let seed = 20261019;
const rng = () => {
  seed = (seed * 1664525 + 1013904223) % 4294967296;
  return seed / 4294967296;
};

const rows: string[] = [];
for (let hi = 12; hi >= 0; hi--) {
  for (let lo = hi; lo >= 0; lo--) {
    for (const suited of hi === lo ? [false] : [true, false]) {
      const a = hi * 4;
      const b = lo * 4 + (suited ? 0 : 1);
      const stub = Array.from({ length: 52 }, (_, i) => i).filter((c) => c !== a && c !== b);
      const deck = stub.slice();
      let won = 0;
      const seven1 = [a, b, 0, 0, 0, 0, 0];
      const seven2 = [0, 0, 0, 0, 0, 0, 0];
      for (let s = 0; s < SAMPLES; s++) {
        // Opponent's two cards from the range, by rejection, then five board cards.
        let p = 0;
        const swap = (i: number) => {
          const j = i + Math.floor(rng() * (deck.length - i));
          const t = deck[i];
          deck[i] = deck[j];
          deck[j] = t;
        };
        for (let tries = 0; tries < 50; tries++) {
          swap(0);
          swap(1);
          if (randomPercentile(deck[0], deck[1]) < TOP) break;
        }
        p = 2;
        for (let i = p; i < p + 5; i++) swap(i);
        for (let i = 0; i < 5; i++) seven1[2 + i] = seven2[2 + i] = deck[2 + i];
        seven2[0] = deck[0];
        seven2[1] = deck[1];
        const x = evaluate(seven1);
        const y = evaluate(seven2);
        won += x > y ? 1 : x === y ? 0.5 : 0;
      }
      const key = hi * 26 + lo * 2 + (suited ? 1 : 0);
      rows.push(`  [${key}, ${(won / SAMPLES).toFixed(4)}],`);
    }
  }
}

writeFileSync(
  new URL('../src/engine/preflopVsRange.ts', import.meta.url),
  `// Generated by scripts/preflop-vs-range.ts — do not edit by hand.
// All-in equity of each starting hand against the top ${TOP * 100}% of hands (${SAMPLES.toLocaleString('en')} samples each).
// Key: hi * 26 + lo * 2 + (suited ? 1 : 0), ranks 0 = deuce .. 12 = ace.
export const PREFLOP_VS_RANGE = new Map<number, number>([
${rows.join('\n')}
]);
`,
);
console.log('wrote', rows.length, 'hand classes');
