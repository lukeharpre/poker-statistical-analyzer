// Generates src/engine/preflopEquity.ts: each starting hand's all-in equity against one
// random hand, by Monte Carlo. Run: npx vite-node scripts/preflop-equity.ts
import { writeFileSync } from 'node:fs';
import { evaluate } from '../src/engine/evaluator';

const SAMPLES = 400_000; // standard error ≈ 0.08 percentage points per hand class

let seed = 20261018;
const rng = () => {
  seed = (seed * 1664525 + 1013904223) % 4294967296;
  return seed / 4294967296;
};

const rows: string[] = [];
for (let hi = 12; hi >= 0; hi--) {
  for (let lo = hi; lo >= 0; lo--) {
    for (const suited of hi === lo ? [false] : [true, false]) {
      const a = hi * 4;
      const b = lo * 4 + (suited ? 0 : 1);
      const stub = Array.from({ length: 52 }, (_, i) => i).filter((c) => c !== a && c !== b);
      const deck = stub.slice();
      let won = 0;
      const seven1 = [a, b, 0, 0, 0, 0, 0];
      const seven2 = [0, 0, 0, 0, 0, 0, 0];
      for (let s = 0; s < SAMPLES; s++) {
        // partial Fisher-Yates: 2 opponent cards + 5 board cards
        for (let i = 0; i < 7; i++) {
          const j = i + Math.floor(rng() * (deck.length - i));
          const t = deck[i];
          deck[i] = deck[j];
          deck[j] = t;
        }
        for (let i = 0; i < 5; i++) seven1[2 + i] = seven2[2 + i] = deck[2 + i];
        seven2[0] = deck[0];
        seven2[1] = deck[1];
        const x = evaluate(seven1);
        const y = evaluate(seven2);
        won += x > y ? 1 : x === y ? 0.5 : 0;
      }
      const key = hi * 26 + lo * 2 + (suited ? 1 : 0);
      rows.push(`  [${key}, ${(won / SAMPLES).toFixed(4)}],`);
    }
  }
}

writeFileSync(
  new URL('../src/engine/preflopEquity.ts', import.meta.url),
  `// Generated by scripts/preflop-equity.ts — do not edit by hand.
// All-in equity of each starting hand against one random hand (${SAMPLES.toLocaleString('en')} samples each).
// Key: hi * 26 + lo * 2 + (suited ? 1 : 0), ranks 0 = deuce .. 12 = ace.
export const PREFLOP_EQUITY = new Map<number, number>([
${rows.join('\n')}
]);
`,
);
console.log('wrote', rows.length, 'hand classes');
