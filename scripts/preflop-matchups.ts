// Generates src/engine/preflopMatchups.ts: the all-in equity of every starting-hand class
// against every other (169 × 169), by Monte Carlo over the suit combinations and boards.
// Push/fold equilibria (src/engine/pushfold.ts) are solved from it.
//   npx vite-node scripts/preflop-matchups.ts -- <shard> <shards>   one part, to a JSON file
//   npx vite-node scripts/preflop-matchups.ts -- merge <shards>     the parts into the table
// e.g. for i in 0 1 2 3 4 5 6 7; do npx vite-node scripts/preflop-matchups.ts -- $i 8 & done; wait
import { readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { evaluate } from '../src/engine/evaluator';
import { CLASS_KEYS, classCombos, encodeEquities } from '../src/engine/pushfold';

const SAMPLES = 60_000; // standard error ≤ 0.2 percentage points per matchup
const part = (i: number) => `${tmpdir()}/preflop-matchups.${i}.json`;
const n = CLASS_KEYS.length;
const pairs: [number, number][] = [];
for (let i = 0; i < n; i++) for (let j = i + 1; j < n; j++) pairs.push([i, j]);

const [cmd, count] = process.argv.slice(-2);
const shards = Number(count);

if (cmd === 'merge') {
  const eq = new Float64Array(n * n).fill(0.5);
  for (let s = 0; s < shards; s++) {
    const got: [number, number, number][] = JSON.parse(readFileSync(part(s), 'utf8'));
    for (const [i, j, e] of got) {
      eq[i * n + j] = e;
      eq[j * n + i] = 1 - e;
    }
  }
  writeFileSync(
    'src/engine/preflopMatchups.ts',
    `// Generated by scripts/preflop-matchups.ts — do not edit by hand.\n` +
      `// All-in equity of each starting-hand class against each other (${SAMPLES.toLocaleString()} samples a matchup),\n` +
      `// row-major over CLASS_KEYS, two base-64 characters a value (0..4095 of 1).\n` +
      `export const PREFLOP_MATCHUPS = '${encodeEquities(eq)}';\n`,
  );
  console.log('written');
} else {
  const shard = Number(cmd);
  let seed = 20261029 + shard * 7919;
  const rng = () => {
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
    return seed / 4294967296;
  };
  const combos = CLASS_KEYS.map(classCombos);
  const used = new Uint8Array(52);
  const h1 = [0, 0, 0, 0, 0, 0, 0];
  const h2 = [0, 0, 0, 0, 0, 0, 0];
  const out: [number, number, number][] = [];
  for (let p = shard; p < pairs.length; p += shards) {
    const [i, j] = pairs[p];
    const ci = combos[i];
    const cj = combos[j];
    let won = 0;
    for (let s = 0; s < SAMPLES; s++) {
      used.fill(0);
      const a = ci[Math.floor(rng() * ci.length)];
      let b = cj[Math.floor(rng() * cj.length)];
      while (b[0] === a[0] || b[0] === a[1] || b[1] === a[0] || b[1] === a[1]) b = cj[Math.floor(rng() * cj.length)];
      used[a[0]] = used[a[1]] = used[b[0]] = used[b[1]] = 1;
      h1[0] = a[0];
      h1[1] = a[1];
      h2[0] = b[0];
      h2[1] = b[1];
      for (let k = 2; k < 7; k++) {
        let c = Math.floor(rng() * 52);
        while (used[c]) c = Math.floor(rng() * 52);
        used[c] = 1;
        h1[k] = h2[k] = c;
      }
      const x = evaluate(h1);
      const y = evaluate(h2);
      won += x > y ? 1 : x === y ? 0.5 : 0;
    }
    out.push([i, j, won / SAMPLES]);
    if (shard === 0 && out.length % 200 === 0) console.log(`${out.length * shards} of ${pairs.length}`);
  }
  writeFileSync(part(shard), JSON.stringify(out));
}
